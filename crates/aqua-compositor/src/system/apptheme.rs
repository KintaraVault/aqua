/// User stylesheet for GTK 4 / libadwaita (appended to the window-controls CSS).
pub fn gtk4_css(accent: &str) -> String {
    let acc = accent_hex(accent, 1.0);
    let acc_text = accent_hex(accent, 0.92);
    let acc_dark_text = accent_hex(accent, 1.15);
    let mut s = String::from("\n/* macOS 26 look (Settings → Appearance → Style other apps) */\n:root {\n");
    s += &format!("  --accent-bg-color: {acc}; --accent-color: {acc_text}; --accent-fg-color: #ffffff;\n");
    s += &vars4(&LIGHT);
    s += "}\n@media (prefers-color-scheme: dark) {\n:root {\n";
    s += &format!("  --accent-color: {acc_dark_text};\n");
    s += &vars4(&DARK);
    s += "}\n}\n";
    s += GTK4_RULES;
    s
}

