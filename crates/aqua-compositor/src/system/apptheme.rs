/// `#aarrggbb` from a `#rrggbb` (or keeps `#aarrggbb`).
fn argb(c: &str, alpha: u8) -> String {
    let h = c.trim_start_matches('#');
    if h.len() == 8 {
        return format!("#{h}");
    }
    format!("#{alpha:02x}{h}")
}

/// qt6ct colour scheme: QPalette roles 0‥21 (WindowText … PlaceholderText, Accent) for the
/// active, disabled and inactive groups.
pub fn qt_color_scheme(dark: bool, accent: &str) -> String {
    let acc = accent_hex(accent, 1.0);
    let (win, base, alt, text, button, light, mid, darkc, shadow, tip, tip_fg, placeholder, link) = if dark {
        (
            "#232325", "#1c1c1e", "#262628", "#f5f5f7", "#3a3a3c", "#4a4a4d", "#2c2c2e", "#141416", "#000000",
            "#3a3a3c", "#f5f5f7", "#8e8e93", "#4da3ff",
        )
    } else {
        (
            "#f3f3f5", "#ffffff", "#f5f5f7", "#1d1d1f", "#ffffff", "#ffffff", "#d1d1d6", "#a1a1a6", "#7f7f7f",
            "#ffffff", "#1d1d1f", "#8e8e93", "#0a66d0",
        )
    };
    let midlight = if dark { "#333335" } else { "#e5e5ea" };
    let roles = |text_c: &str, btn_text: &str, hl: &str| {
        [
            text_c, button, light, midlight, darkc, mid, text_c, "#ffffff", btn_text, base, win, shadow, hl, "#ffffff",
            link, link, alt, "#000000", tip, tip_fg, placeholder, acc.as_str(),
        ]
        .iter()
        .map(|c| argb(c, 0xff))
        .collect::<Vec<_>>()
        .join(", ")
    };
    let dis = if dark { "#6e6e73" } else { "#b0b0b5" };
    let inactive_hl = if dark { "#3a3a3c" } else { "#d4d4d9" };
    format!(
        "# generated by aqua\n[ColorScheme]\nactive_colors={}\ndisabled_colors={}\ninactive_colors={}\n",
        roles(text, text, &acc),
        roles(dis, dis, inactive_hl),
        roles(text, text, &acc)
    )
}

