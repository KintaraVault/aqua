//! macOS 26 ("Tahoe") look for third-party toolkits.
//!
//! * **GTK 4 / libadwaita** — libadwaita ignores themes, but loads the user stylesheet
//!   `~/.config/gtk-4.0/gtk.css` on top of its own. We override its CSS variables (window,
//!   view, sidebar, accent colours, window radius) for light *and* dark (`@media
//!   (prefers-color-scheme: dark)`, so live appearance switches work) and restyle controls:
//!   glass capsule toolbar buttons, rounded push buttons and fields with an accent focus
//!   ring, capsule search fields, macOS switches, accent-highlighted menus.
//! * **GTK 3** — a real theme, `Aqua` / `Aqua-dark` in `~/.local/share/themes`: GTK's
//!   built-in Adwaita plus the same look written in GTK 3 CSS.
//! * **Qt** — a `qt6ct`/`qt5ct` configuration (Fusion, Aqua palette with the accent, SF
//!   Pro, a stylesheet with rounded controls, portal dialogs). Used when the qt6ct
//!   platform theme is installed (see `qt_platform_theme`).
