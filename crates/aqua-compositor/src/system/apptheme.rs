/// GTK theme name to set in `settings.ini`: the Aqua theme when app styling is on and the
/// user has not picked another theme (`None`: leave the user's choice alone).
pub fn gtk_theme_choice(current: Option<&str>, dark: bool, style_apps: bool) -> Option<String> {
    let cur = current.unwrap_or("");
    let ours = matches!(cur, "Aqua" | "Aqua-dark");
    let stock = matches!(cur, "" | "Adwaita" | "Adwaita-dark" | "Default");
    if style_apps && (ours || stock) {
        Some(if dark { "Aqua-dark" } else { "Aqua" }.into())
    } else if !style_apps && ours {
        Some(if dark { "Adwaita-dark" } else { "Adwaita" }.into())
    } else {
        None
    }
}

/// Write the GTK 3 theme (both variants) into `data/themes`.
pub fn install_gtk3_theme(data: &Path, accent: &str) {
    for (name, dark) in [("Aqua", false), ("Aqua-dark", true)] {
        let dir = data.join("themes").join(name);
        super::theming::write_if_ours(&dir.join("gtk-3.0/gtk.css"), &gtk3_theme_css(dark, accent), MARK);
        super::theming::write_if_ours(&dir.join("index.theme"), &gtk3_index_theme(name), "generated by aqua");
    }
}

