/// `#rrggbb` of the accent, scaled by `k` (darker < 1).
pub fn accent_hex(accent: &str, k: f32) -> String {
    let (r, g, b) = aqua_config::accent_rgb(accent);
    let c = |v: f32| (v * k * 255.0).round().clamp(0.0, 255.0) as u8;
    format!("#{:02x}{:02x}{:02x}", c(r), c(g), c(b))
}

